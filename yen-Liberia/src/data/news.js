export const getNewsArticleBySlug = (slug) => {
  return newsArticles.find(
    (article) => article.slug === slug,
  )
}

export const getRelatedNews = (article, limit = 3) => {
  return newsArticles
    .filter((item) => item.id !== article.id)
    .sort((a, b) => {
      const aSameCategory =
        a.category === article.category ? 1 : 0

      const bSameCategory =
        b.category === article.category ? 1 : 0

      return bSameCategory - aSameCategory
    })
    .slice(0, limit)
}